# 3. Спектральный аудит, граф переходов и бутстрэп (Таблица 1)
def safe_zscore(M_arr):
    mean_v = np.mean(M_arr, axis=0)
    std_v = np.std(M_arr, axis=0, ddof=1)
    safe_std = np.where(std_v > 1e-12, std_v, 1.0)
    Z = (M_arr - mean_v) / safe_std
    Z[:, std_v <= 1e-12] = 0.0
    return Z

def run_eurasian_audit(dlnX, yrs, label, n_boot=300, seed=42):
    Z = safe_zscore(dlnX)
    M, N = Z.shape
    U, s, Vt = np.linalg.svd(Z, full_matrices=False)
    u1, v1, v2 = np.take(U, 0, axis=1), np.take(Vt, 0, axis=0), np.take(Vt, 1, axis=0)
    var1 = (s.item(0)**2) / np.sum(s**2) * 100.0
    var2 = (s.item(1)**2) / np.sum(s**2) * 100.0
    pr_u1 = (1.0 / np.sum(u1**4) - 1.0) / (M - 1.0)
    pr_v1 = (1.0 / np.sum(v1**4) - 1.0) / (N - 1.0)

    rng = np.random.default_rng(seed)
    sub_M = int(np.floor(M * 0.8))
    b_pru, b_prv = [], []
    for _ in range(n_boot):
        idx = np.sort(rng.choice(M, size=sub_M, replace=False))
        Ub, _, Vtb = np.linalg.svd(safe_zscore(dlnX[idx, :]), full_matrices=False)
        u1b, v1b = np.take(Ub, 0, axis=1), np.take(Vtb, 0, axis=0)
        b_pru.append((1.0 / np.sum(u1b**4) - 1.0) / (sub_M - 1.0))
        b_prv.append((1.0 / np.sum(v1b**4) - 1.0) / (N - 1.0))

    dist_mat = squareform(pdist(Z, metric='euclidean'))
    sigma_med = np.median(dist_mat[np.triu_indices(M, k=1)])
    W_full = np.exp(-(dist_mat**2) / (2.0 * sigma_med**2))
    np.fill_diagonal(W_full, 0.0)
    A = np.zeros((M, M))
    for i in range(M):
        for j in np.argsort(dist_mat[i, :])[1:7]:
            A[i, j] = W_full[i, j]
            A[j, i] = W_full[j, i]
    deg = np.sum(A, axis=1)
    d_inv_sqrt = np.diag(1.0 / np.sqrt(np.maximum(deg, 1e-12)))
    _, eigvecs = np.linalg.eigh(np.eye(M) - d_inv_sqrt @ A @ d_inv_sqrt)
    psi2 = np.take(eigvecs, 1, axis=1)
    best_p, best_tau = 1.0, -1
    for tau in range(12, M - 12):
        _, pval = mannwhitneyu(psi2[:tau], psi2[tau:], alternative='two-sided')
        if pval < best_p:
            best_p, best_tau = pval, tau

    print(f"{label:<38} | M={M:3d} | Var1={var1:4.1f}% | Var2={var2:4.1f}% | PR(u1)={pr_u1:.3f} [{np.percentile(b_pru, 2.5):.2f}, {np.percentile(b_pru, 97.5):.2f}] | PR(v1)={pr_v1:.3f} [{np.percentile(b_prv, 2.5):.2f}, {np.percentile(b_prv, 97.5):.2f}] | Break={int(yrs.item(best_tau))} (p={best_p:.4f})")
    pvals_scan = [mannwhitneyu(psi2[:tau], psi2[tau:], alternative='two-sided').pvalue for tau in range(12, M - 12)]
    return v1, v2, yrs, pvals_scan

